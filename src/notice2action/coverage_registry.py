"""
Language Coverage Registry for SuchnaSetu AI.
Tracks verified recognition capabilities, script metadata, model availability,
benchmarked CER/WER profiles, and adapter status across all 22 Indian Scheduled Languages
(Eighth Schedule of the Constitution of India) plus English.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Any
from pathlib import Path


@dataclass
class LanguageCoverageItem:
    code: str
    iso_639_1: str
    iso_639_2: str
    name: str
    native_name: str
    script: str
    unicode_range: str
    primary_engine: str
    primary_model: str
    secondary_engine: str
    secondary_model: str
    supports_printed: bool
    supports_scanned: bool
    model_installed: bool
    status: str  # "verified_production", "supported_installed", "adapter_ready_model_needed", "extensible_adapter"
    cer_percent: Optional[float]
    wer_percent: Optional[float]
    known_limitations: str
    historical_evidence: str

    def to_dict(self) -> Dict[str, Any]:
        return {
            "code": self.code,
            "iso_639_1": self.iso_639_1,
            "iso_639_2": self.iso_639_2,
            "name": self.name,
            "native_name": self.native_name,
            "script": self.script,
            "unicode_range": self.unicode_range,
            "primary_engine": self.primary_engine,
            "primary_model": self.primary_model,
            "secondary_engine": self.secondary_engine,
            "secondary_model": self.secondary_model,
            "supports_printed": self.supports_printed,
            "supports_scanned": self.supports_scanned,
            "model_installed": self.model_installed,
            "status": self.status,
            "cer_percent": self.cer_percent,
            "wer_percent": self.wer_percent,
            "known_limitations": self.known_limitations,
            "historical_evidence": self.historical_evidence,
        }


