def get_language_coverage(code_or_alias: str) -> Optional[LanguageCoverageItem]:
    """Retrieves the coverage and capability record for a given language code or alias."""
    clean = code_or_alias.lower().strip()
    # Direct lookup
    if clean in SCHEDULED_LANGUAGES_REGISTRY:
        return SCHEDULED_LANGUAGES_REGISTRY[clean]
    # Alias lookup
    for item in SCHEDULED_LANGUAGES_REGISTRY.values():
        if clean in (item.iso_639_1, item.iso_639_2, item.name.lower()):
            return item
    return None


def get_all_coverage_items() -> List[LanguageCoverageItem]:
    """Returns coverage items for all 22 Indian Scheduled Languages plus English."""
    return list(SCHEDULED_LANGUAGES_REGISTRY.values())


def get_coverage_summary() -> Dict[str, Any]:
    """Returns an executive breakdown of language coverage status."""
    total = len(SCHEDULED_LANGUAGES_REGISTRY)
    verified = [i for i in SCHEDULED_LANGUAGES_REGISTRY.values() if i.status == "verified_production"]
    installed = [i for i in SCHEDULED_LANGUAGES_REGISTRY.values() if i.model_installed]
    adapter_ready = [i for i in SCHEDULED_LANGUAGES_REGISTRY.values() if i.status == "adapter_ready_model_needed"]
    extensible = [i for i in SCHEDULED_LANGUAGES_REGISTRY.values() if i.status == "extensible_adapter"]

    return {
        "total_languages": total,
        "verified_production_count": len(verified),
        "installed_model_count": len(installed),
        "adapter_ready_count": len(adapter_ready),
        "extensible_adapter_count": len(extensible),
        "installed_languages": [i.name for i in installed],
        "adapter_ready_languages": [i.name for i in adapter_ready],
        "extensible_adapter_languages": [i.name for i in extensible],
    }
